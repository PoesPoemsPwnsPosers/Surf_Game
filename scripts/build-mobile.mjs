// Builds the game as ONE self-contained HTML file and hands it to the Expo app.
//
//   node scripts/build-mobile.mjs        (or: npm run build:mobile)
//
// Output:
//   mobile/generated/game.html     the game in a single file (handy to open in a browser)
//   mobile/generated/gameHtml.js   the same file as a JavaScript string, which the app loads
//
// The Expo app shows the game in a WebView. Giving it one string with everything inside means
// the app works offline and needs no web server.
import { mkdir, readFile, readdir, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'vite';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const tmp = path.join(root, 'node_modules', '.surf-mobile-build');
const outDir = path.join(root, 'mobile', 'generated');

await build({
  root,
  configFile: false,
  logLevel: 'warn',
  base: './',
  build: {
    outDir: tmp,
    emptyOutDir: true,
    // One script, one stylesheet, nothing loaded later.
    assetsInlineLimit: 100_000_000,
    cssCodeSplit: false,
    rolldownOptions: { output: { codeSplitting: false } },
  },
});

const assets = await readdir(path.join(tmp, 'assets'));
const scripts = assets.filter((f) => f.endsWith('.js'));
const styles = assets.filter((f) => f.endsWith('.css'));
if (scripts.length !== 1 || styles.length !== 1 || assets.length !== 2) {
  throw new Error(`Expected exactly one script and one stylesheet, got: ${assets.join(', ')}`);
}
const js = await readFile(path.join(tmp, 'assets', scripts[0]), 'utf8');
const css = await readFile(path.join(tmp, 'assets', styles[0]), 'utf8');
let html = await readFile(path.join(tmp, 'index.html'), 'utf8');

const linkTag = /<link[^>]+rel="stylesheet"[^>]*>/;
const scriptTag = /<script[^>]+type="module"[^>]*><\/script>/;
if (!linkTag.test(html) || !scriptTag.test(html)) throw new Error('index.html does not have the expected script and stylesheet tags');
// Function replacements, so a "$" in the code is not read as a replacement pattern.
html = html.replace(scriptTag, () => '');
html = html.replace(linkTag, () => `<style>\n${css}\n</style>`);
// The script goes at the end of the body, where a module script would have run anyway.
html = html.replace('</body>', () => `<script type="module">\n${js.replace(/<\/script/g, '<\\/script')}\n</script>\n</body>`);
if (/(src|href)="\.?\/?assets\//.test(html)) throw new Error('The single file still points at a separate asset');

await mkdir(outDir, { recursive: true });
await writeFile(path.join(outDir, 'game.html'), html);
await writeFile(
  path.join(outDir, 'gameHtml.js'),
  `// Generated by scripts/build-mobile.mjs. Do not edit: run "npm run build:mobile" in the repo root.\nmodule.exports = ${JSON.stringify(html)};\n`,
);
await rm(tmp, { recursive: true, force: true });
console.log(`mobile/generated/game.html  ${(html.length / 1024).toFixed(0)} KB`);
